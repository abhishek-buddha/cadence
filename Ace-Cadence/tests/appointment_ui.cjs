// Runs against the real isolated review stack through its local SSH tunnel.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const baseURL = process.env.REVIEW_BASE_URL || 'http://127.0.0.1:18080';
assert(['127.0.0.1', 'localhost'].includes(new URL(baseURL).hostname), 'Use the isolated localhost review stack');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  const appointmentType = 'Browser review ' + Date.now();
  const admin = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  admin.on('pageerror', e => errors.push(e.message));
  await admin.addInitScript(() => {
    sessionStorage.setItem('cadence_auth', '1');
    sessionStorage.setItem('cadence_session_token', 'review-admin-session');
    sessionStorage.setItem('cadence_current_user', JSON.stringify({ userId: '2', name: 'Review Admin', email: 'admin@example.test', role: 'admin' }));
  });
  await admin.goto(`${baseURL}/master-data`);
  await admin.getByRole('button', { name: 'Edit', exact: true }).first().click();
  await admin.getByLabel('Mobile number (with country code)').fill('+14155550124');
  await admin.screenshot({ path: path.join(process.env.TEMP, 'cadence-patient-mobile-edit.png'), fullPage: true, animations: 'disabled' });
  await admin.getByRole('button', { name: 'Update Patient', exact: true }).click();
  await admin.getByRole('button', { name: 'Update Patient', exact: true }).waitFor({ state: 'detached' });
  await admin.getByRole('button', { name: 'Edit', exact: true }).first().click();
  assert.equal(await admin.getByLabel('Mobile number (with country code)').inputValue(), '+14155550124');
  await admin.close();
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => {
    sessionStorage.setItem('cadence_auth', '1');
    sessionStorage.setItem('cadence_session_token', 'review-session');
    sessionStorage.setItem('cadence_current_user', JSON.stringify({ userId: '1', name: 'Review Operator', email: 'review@example.test', role: 'operator' }));
  });
  await page.goto(`${baseURL}/appointments`);
  await page.getByRole('link', { name: 'Review Patient', exact: true }).first().waitFor();
  await page.getByRole('row').filter({ hasText: 'Unanswered reminder review' }).first().getByText('No Answer', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(process.env.TEMP, 'cadence-appointments-list.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Create appointment', exact: true }).click();
  await page.screenshot({ path: path.join(process.env.TEMP, 'cadence-appointments-form.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('combobox', { name: /^Patient/ }).selectOption('1');
  assert.equal(await page.getByLabel('Patient mobile').inputValue(), '+14155550124', 'Use saved master-data phone');
  await page.getByRole('combobox', { name: /^Provider/ }).selectOption('1');
  await page.getByLabel('Patient mobile').fill('+14155550123');
  await page.getByLabel('Appointment type', { exact: true }).fill(appointmentType);
  await page.getByLabel('Appointment date and time').fill('2027-01-20T14:30');
  await page.getByLabel('Clinic timezone').fill('America/New_York');
  await page.getByLabel('Location', { exact: true }).fill('Review location');
  await page.getByLabel('Patient instructions').fill('Bring your existing paperwork.');
  await page.getByRole('button', { name: 'Save appointment', exact: true }).click();
  await page.getByText(appointmentType, { exact: true }).waitFor();
  await page.getByRole('row').filter({ hasText: appointmentType }).getByRole('link', { name: 'Review Patient' }).click();
  await page.getByRole('heading', { name: 'Patient Demographics', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Insurance & Plan', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Call History, Transcripts & Recordings', exact: true }).waitFor();
  await page.getByText('Not Called', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: 'Call patient', exact: true }).isEnabled());
  await page.screenshot({ path: path.join(process.env.TEMP, 'cadence-appointments-details.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Edit appointment', exact: true }).click();
  await page.getByLabel('Location', { exact: true }).fill('Updated browser location');
  await page.getByRole('button', { name: 'Save appointment', exact: true }).click();
  await page.getByRole('button', { name: 'Save appointment', exact: true }).waitFor({ state: 'detached' });
  await page.getByText('Updated browser location', { exact: true }).first().waitFor();
  await page.getByRole('heading', { name: 'Appointment Details', exact: true }).waitFor();
  assert(await page.getByRole('button', { name: 'Call patient', exact: true }).isEnabled());
  const appointmentId = page.url().split('/').pop();
  const headers = { Authorization: 'Bearer review-session' };
  const appointment = await (await page.request.get(`${baseURL}/api/appointments/${appointmentId}`, { headers })).json();
  const fields = ['patient_id','provider_id','patient_phone','appointment_type','scheduled_at','timezone','location','instructions','notes','status'];
  const body = Object.fromEntries(fields.map(key => [key, appointment[key]]));
  const rescheduled = await page.request.put(`${baseURL}/api/appointments/${appointmentId}`, { headers, data: { ...body, scheduled_at: '2027-02-20T15:45' } });
  assert(rescheduled.ok(), await rescheduled.text());
  await page.getByText('Rescheduled', { exact: true }).waitFor();
  await page.getByText('2027-02-20 3:45 PM', { exact: true }).first().waitFor();
  assert(await page.getByText('2027-01-20 2:30 PM', { exact: true }).isVisible(), 'Keep original date after rescheduling');
  const cancelled = await page.request.put(`${baseURL}/api/appointments/${appointmentId}`, { headers, data: { ...body, scheduled_at: '2027-02-20T15:45', status: 'cancelled' } });
  assert(cancelled.ok(), await cancelled.text());
  await page.getByText('Cancelled', { exact: true }).first().waitFor();
  assert(await page.getByRole('button', { name: 'Call patient', exact: true }).isDisabled());
  await page.getByRole('link', { name: 'Back to Appointments', exact: true }).click();
  assert.equal(await page.getByRole('tablist', { name: 'Appointment views' }).count(), 0);
  const cancelledRow = page.getByRole('row').filter({ hasText: appointmentType });
  await cancelledRow.getByText('Cancelled', { exact: true }).waitFor();
  await cancelledRow.getByRole('link', { name: 'Review Patient' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('main').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: path.join(process.env.TEMP, 'cadence-appointments-mobile.png'), fullPage: true, animations: 'disabled' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile detail page must not overflow');
  assert((await page.locator('main').boundingBox()).width >= 380, 'Navigation must not squeeze the mobile details');
  await page.getByRole('button', { name: 'Navigation', exact: true }).click();
  assert(await page.getByRole('link', { name: 'My Queue', exact: true }).isVisible());
  await page.getByRole('button', { name: 'Close navigation', exact: true }).last().click();
  await page.goto(`${baseURL}/appointments/scheduling/1`);
  assert.equal(await page.getByText(/Thomas is navigating the IVR/).count(), 0);
  await page.getByText('Call #1', { exact: false }).click();
  await page.getByText(/^Agent: Hello\s+Patient: Hello$/).waitFor();
  await page.screenshot({ path: path.join(process.env.TEMP, 'cadence-appointments-history.png'), fullPage: true, animations: 'disabled' });
  if (process.env.REVIEW_TRANSCRIPT_CALL_ID) {
    const call = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: `Call #${process.env.REVIEW_TRANSCRIPT_CALL_ID} \u00b7` }) });
    await call.locator('summary').click();
    await call.getByRole('heading', { name: 'Operator transcript', exact: true }).waitFor();
    const transcript = await call.getByRole('heading', { name: 'Operator transcript', exact: true }).locator('+ p').textContent();
    assert(transcript.toLowerCase().includes('insurance card'));
    assert(new Set(transcript.split('\n').map(line => line.split(':')[0])).size >= 2);
    assert.equal(await call.getByRole('button', { name: 'Generate operator transcript' }).count(), 0);
    await page.screenshot({ path: path.join(process.env.TEMP, 'cadence-operator-transcript.png'), fullPage: true, animations: 'disabled' });
    console.log('PASS: real two-speaker operator transcript displayed in appointment history');
  }
  assert.deepEqual(errors, []);
  console.log('PASS: existing tab layouts, Not Called/No Answer tags, creation, real-time reschedule/cancel, original slot, reminder navigation, history and mobile rendering without React errors');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
